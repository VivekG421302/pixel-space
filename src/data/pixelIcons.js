export const PATHS = Object.fromEntries(
  Object.entries(ICONS).map(([name, rows]) => {
    let d = '';
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] !== '#') continue;
        const x0 = x;
        while (x < row.length && row[x] === '#') x++;
        d += `M${x0} ${y}h${x - x0}v1h-${x - x0}z`;
        x--;
      }
    });
    return [name, d];
  })
);

// CSS cursor built from an icon (white outline so it shows on any background). hx / hy is the hot spot in px (32 px cursor).
const cursorCache = {};
export function iconCursor(name, hx, hy, fallback = 'crosshair') {
  const k = `${name}:${hx}:${hy}`;
  if (!cursorCache[k]) {
    const p = PATHS[name];
    const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='32' height='32' viewBox='0 0 16 16' shape-rendering='crispEdges'><path d='${p}' fill='#fff' stroke='#fff' stroke-width='1.6' stroke-linejoin='round'/><path d='${p}' fill='#202020'/></svg>`;
    cursorCache[k] = `url("data:image/svg+xml,${encodeURIComponent(svg)}") ${hx} ${hy}, ${fallback}`;
  }
  return cursorCache[k];
}
